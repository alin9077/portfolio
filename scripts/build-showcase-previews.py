#!/usr/bin/env python3
"""Build responsive showcase previews while preserving originals for the viewer."""
import argparse
import hashlib
import json
import re
import subprocess
from urllib.parse import quote
from pathlib import Path
from PIL import Image, ImageOps


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--node', required=True, help='Available Node executable')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root = args.root.resolve()
    extract = """const fs=require('node:fs'),vm=require('node:vm');const c={window:{}};
vm.runInNewContext(fs.readFileSync(process.argv[1],'utf8'),c);
console.log(JSON.stringify([...new Set(Object.values(c.window.H_PROJECTS).flatMap(p=>[...(p.media?.showcase?.images||[]),...(p.subs||[]).flatMap(s=>s.showcase?.images||[])].map(i=>i.image)))]));"""
    result = subprocess.run([args.node, '-e', extract, str(root / 'portfolio-content.js')], check=True, text=True, capture_output=True)
    paths = json.loads(result.stdout)
    output = root / 'assets/showcase/previews'
    output.mkdir(parents=True, exist_ok=True)
    metadata = {}
    totals = {'original_bytes': 0, 'largest_preview_bytes': 0, 'fallback_preview_bytes': 0, 'images': len(paths), 'generated_files': 0}
    for source in paths:
        path = (root / source).resolve()
        if not path.is_relative_to(root):
            raise ValueError(f'Asset is outside this project: {source}')
        with Image.open(path) as opened:
            image = ImageOps.exif_transpose(opened)
            width, height = image.size
            image = image.convert('RGBA' if 'A' in image.getbands() else 'RGB')
            icc = opened.info.get('icc_profile')
            candidates = {}
            def add(candidate):
                with Image.open(candidate) as preview:
                    w, h = preview.size
                if abs(h / w - height / width) > .01:
                    return
                if w not in candidates or candidate.stat().st_size < candidates[w].stat().st_size:
                    candidates[w] = candidate
            # Reuse the existing image family, with actual measured descriptors.
            if re.search(r'-(1440|1600)\.webp$', source):
                for size in (480, 720, 960):
                    sibling = root / re.sub(r'-(1440|1600)\.webp$', f'-{size}.webp', source)
                    if sibling.is_file():
                        add(sibling)
            if path.suffix.lower() == '.webp' and width <= 1440:
                add(path)
            stem = re.sub(r'[^a-z0-9-]+', '-', path.stem.lower()).strip('-')
            token = hashlib.sha256(source.encode()).hexdigest()[:8]
            for size in sorted(set(min(size, width) for size in (480, 960, 1440))):
                if size in candidates:
                    continue
                destination = output / f'{stem}-{token}-{size}.webp'
                if not destination.exists() or destination.stat().st_mtime < max(path.stat().st_mtime, Path(__file__).stat().st_mtime):
                    preview = image.resize((size, max(1, round(height * size / width))), Image.Resampling.LANCZOS)
                    options = {'quality': 82, 'method': 6}
                    if icc:
                        options['icc_profile'] = icc
                    preview.save(destination, 'WEBP', **options)
                add(destination)
                totals['generated_files'] += 1
            widths = sorted(candidates)
            fallback = next((w for w in widths if w >= min(960, width)), widths[-1])
            relative = lambda p: p.relative_to(root).as_posix()
            metadata[source] = {'src': relative(candidates[fallback]), 'srcset': ', '.join(f'{quote(relative(candidates[w]))} {w}w' for w in widths), 'width': width, 'height': height}
            totals['original_bytes'] += path.stat().st_size
            totals['largest_preview_bytes'] += candidates[widths[-1]].stat().st_size
            totals['fallback_preview_bytes'] += candidates[fallback].stat().st_size
    manifest = root / 'assets/showcase/manifest.js'
    manifest.write_text('/* Generated by scripts/build-showcase-previews.py; originals remain available in the viewer. */\nwindow.H_SHOWCASE_ASSETS = ' + json.dumps(metadata, ensure_ascii=False, separators=(',', ':')) + ';\n')
    report = root / 'output/project-model/image-optimization.json'
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(json.dumps(totals, indent=2) + '\n')
    print(json.dumps(totals, indent=2))


if __name__ == '__main__':
    main()
